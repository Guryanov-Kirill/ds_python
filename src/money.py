# Эта программа решает задачу размена суммы с использованием "монет",
# номиналы которых равны длинам введенных имени, фамилии и отчества

# Получаем длины имени, фамилии и отчества, вычесляем их длину
name = len(str(input("введите имя")))
surname = len(str(input("введите фамилию")))
otch = len(str(input("введите отчество")))

# Запрашиваем у пользователя сумму, которую нужно разменять
summa = int(input("введите сумму"))

# Создаем список "монет", номиналов для размена
coins = [name, surname, otch]

# Создаем массив для динамического программирования, где:
# exchange[i] будет содержать способ размена суммы i или False, если размен невозможен
exchange = [False] * (summa + 1)

# Сумму 0 можно разменять нулевым количеством монет
exchange[0] = "0"

# Используем динамическое программирование
for coin in coins:
    for i in range(coin, summa + 1):
        # Если предыдущую сумму (i - coin) можно разменять
        if exchange[i - coin] != False:
            # Если текущую сумму i еще нельзя разменять
            if exchange[i] == False:
                # Проверяем, делится ли сумма i нацело на номинал монеты
                if i % coin == 0:
                    # Если да, то размен только монетами текущего номинала
                    exchange[i] = f"{coin}*{i // coin}"
                else:
                    # Если нет, комбинируем текущие монеты с предыдущим разменом
                    exchange[i] = f"{coin}*{i // coin}+{exchange[i - coin]}"

            # Проверяем, достигли ли мы целевой суммы
            if exchange[summa] != False:
                print(exchange[summa])

if exchange[summa] != False:
    # Выводим найденный способ размена
    print(exchange[summa])
else:
    # Если размен невозможен, выводим '-42!'
    print("-42!")
